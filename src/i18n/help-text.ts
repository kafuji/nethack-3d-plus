/** The #version document. Identifiers and Lua's license text stay as written. */
function translateVersionDocument(lines: readonly string[]): string | null {
  if (!/^\S+ NetHack Version /.test(lines.find((line) => line.trim())?.trim() ?? "")) return null;
  const output: string[] = [];
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index].trimEnd();
    const lua = /^NetHack (\S+) uses the 'Lua' interpreter to process some data:$/.exec(line);
    if (lua) {
      output.push(`NetHack ${lua[1]} は一部のデータの処理に 'Lua' インタプリタを使います（ライセンス文は原文のまま）：`, ...lines.slice(index + 1).map((rest) => rest.trimEnd()));
      break;
    }
    if (line === "Options compiled into this edition:") {
      const features: string[] = [];
      while (lines[index + 1]?.trim()) features.push(lines[++index].trim());
      output.push(versionHeadings[line], `    ${features.join(" ").replace(/\.$/, "").split(/,\s+(?:and\s+)?/).map(versionFeature).join("、")}。`);
      continue;
    }
    const built = /^(\S+) NetHack Version (\S+) \S+ - last build (.+)$/.exec(line);
    output.push(built ? `${built[1]} NetHack バージョン ${built[2]}（最終ビルド ${built[3]}）` : Object.prototype.hasOwnProperty.call(versionHeadings, line) ? versionHeadings[line] : line);
  }
  return output.join("\n").replace(/\n+$/, "");
}

