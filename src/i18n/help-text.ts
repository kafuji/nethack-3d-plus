function versionFeature(feature: string): string {
  const files = /^save and bones files accepted from (.+)$/.exec(feature);
  if (files) return `${files[1].replace(/^version /, "バージョン ").replace(/ only$/, "")} のセーブファイルと骨ファイルに対応`;
  return Object.prototype.hasOwnProperty.call(versionFeatures, feature) ? versionFeatures[feature] : feature;
}

